function copy<T>(value: T): T {
  return structuredClone(value);
}

export function getDiscoveredOrganizations(): Organization[] {
  return organizationSeeds.map((seed) => ({
    ...copy(seed),
    postingHistory: opportunitySeeds
      .filter((opportunity) => opportunity.organizationId === seed.id)
      .map((opportunity) => ({ opportunityId: opportunity.id, postedAt: opportunity.publicationDate.toISOString() })),
    createdAt: SEED_SNAPSHOT_AT,
    updatedAt: SEED_SNAPSHOT_AT,
  }));
}

export function getDiscoveredOpportunities(): Opportunity[] {
  const organizations = new Map(getDiscoveredOrganizations().map((organization) => [organization.id, organization]));
  return opportunitySeeds.map((seed) => {
    const organization = organizations.get(seed.organizationId);
    if (!organization) throw new Error(`Discovered-catalog organization ${seed.organizationId} is missing.`);
    return {
      ...copy(seed),
      organization: {
        id: organization.id,
        name: organization.name,
        verificationStatus: organization.verificationStatus,
      },
    };
  });
}
